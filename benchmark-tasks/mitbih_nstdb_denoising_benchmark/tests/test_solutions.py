"""Tests and failure cases for the benchmark solutions.

Each test runs the evaluator on a solution and asserts the documented
invariants.  Success-case scores are compared against ``expected_results.json``
(the reference-solution results, regenerated by
``evaluator.evaluate(reference_solution())``).  Failure cases cover invalid
input, noisy/short signals and edge conditions.
"""
import json
import os
import sys

import numpy as np
import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
PKG_DIR = os.path.dirname(HERE)
sys.path.insert(0, HERE)
sys.path.insert(0, PKG_DIR)

from evaluator import evaluate  # noqa: E402
from reference_solution import reference_solution  # noqa: E402
from starter_solution import starter_solution  # noqa: E402


@pytest.fixture(scope="module")
def expected():
    path = os.path.join(PKG_DIR, "expected_results.json")
    with open(path) as fh:
        return json.load(fh)


def test_reference_matches_expected_results(expected):
    """Regenerating the reference solution on real data reproduces the
    committed expected results (determinism + reference commit)."""
    res = evaluate(reference_solution(), segments=expected["segments_per_cell"])
    assert res["mode"] == expected["mode"], (res["mode"], expected["mode"])
    assert res["overall_score"] == pytest.approx(
        expected["overall_score"], abs=0.05), res["overall_score"]
    assert res["n_cells"] > 0


def test_reference_scores_higher_than_starter():
    """The reference solution beats the naive starter baseline."""
    ref = evaluate(reference_solution(), segments=2)
    start = evaluate(starter_solution(), segments=2)
    assert ref["overall_score"] >= start["overall_score"]


def test_evaluator_structure_and_validity():
    """A solution returning the noisy signal unchanged is structurally
    valid but performs poorly (zero improvement) — it must not score
    like the reference."""
    class Noop:
        def denoise(self, noisy, fs):
            class R:
                signal = np.asarray(noisy, dtype=float)
                method = "noop"
            return R()

    res = evaluate(Noop(), segments=2)
    ref = evaluate(reference_solution(), segments=2)
    assert res["sub_scores"]["structure"] == 1.0
    assert res["overall_score"] < ref["overall_score"]


def test_evaluator_rejects_nan_output():
    class NaNOut:
        def denoise(self, noisy, fs):
            class R:
                signal = np.full(len(noisy), np.nan)
                method = "nan"
            return R()

    res = evaluate(NaNOut(), segments=2)
    assert res["sub_scores"]["numerical_validity"] == 0.0


def test_evaluator_rejects_wrong_shape():
    class WrongShape:
        def denoise(self, noisy, fs):
            class R:
                signal = np.asarray(noisy)[:-5]
                method = "short"
            return R()

    res = evaluate(WrongShape(), segments=2)
    assert res["sub_scores"]["structure"] == 0.0


def test_reference_deterministic():
    r1 = evaluate(reference_solution(), segments=2)
    r2 = evaluate(reference_solution(), segments=2)
    assert r1["overall_score"] == r2["overall_score"]
    assert r1["reproducibility_ok"] is True


def test_synthetic_fallback_mode_runs_offline():
    """With PhysioNet data absent, the evaluator falls back to synthetic
    data and still runs the reference solution end-to-end."""
    # Force the fallback by pointing the evaluator at a bogus data dir.
    import evaluator as ev
    saved = ev._load_real_data
    ev._load_real_data = lambda *a, **k: (None, {})
    try:
        res = evaluate(reference_solution(), segments=2)
    finally:
        ev._load_real_data = saved
    assert res["mode"] == "synthetic"
    assert res["n_cells"] > 0
